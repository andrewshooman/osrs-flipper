"""Refresh data, retrain the production model, and promote it only if it holds up.

    python research/retrain.py              # weekly: collect new days, retrain, compare, promote
    python research/retrain.py --no-collect # retrain on what's already downloaded

Steps:
 1. Download any missing hourly snapshots (research/collect.py logic).
 2. Train a candidate on the last 365 days (same settings as full-year-v1).
 3. Backtest candidate vs the current model on the most recent 14 days with the
    production preset. Both models must be trained without those 14 days, so
    this step trains a holdout copy of each.
 4. Promote only if the candidate's holdout profit is at least 90% of the
    current model's: write models/flip-model.js (the app) and research/models/current/
    (the bot's model directory).
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from backtest import Config, Sim  # noqa: E402
from export_js import export  # noqa: E402
from features import features_chunked, labels_chunked  # noqa: E402
from panel import panel_from_df, read_days  # noqa: E402
from strategy_model import PRESETS, ModelStrategy  # noqa: E402
from train import FlipModel, candidate_mask, fit  # noqa: E402

CURRENT = ROOT / "models" / "current"
APP_MODEL = ROOT.parent / "models" / "flip-model.js"
APP_BOOSTERS = ["fill", "ret", "hours", "fwd4_q10", "fwd4_q50", "fwd4_q90"]


def holdout_profit(P, F, Y, Q, names, start, rounds):
    """Train on everything before `start` (with embargo), backtest from `start`."""
    bars_day = int(86400 // P.step)
    tm = candidate_mask(P, F)
    tm[start - 27:] = False
    m = fit(F, Y, Q, tm, names, rounds=rounds)
    warm = start - 8 * bars_day
    test = P.slice(warm, P.T)
    Ft = {k: v[warm:] for k, v in F.items()}
    r = Sim(test, Config(), ModelStrategy(m, Ft, name="production", **PRESETS["production"])).run(start=start - warm)
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-collect", action="store_true")
    ap.add_argument("--days", type=int, default=365)
    ap.add_argument("--holdout-days", type=int, default=14)
    ap.add_argument("--rounds", type=int, default=200)
    ap.add_argument("--force", action="store_true", help="promote even if the holdout is worse")
    a = ap.parse_args()
    t0 = time.time()

    if not a.no_collect:
        import collect
        collect.collect("1h", 30, rate=3)  # fills any gaps in the last month

    P = panel_from_df(read_days("1h", a.days), "1h", min_trade_frac=0.3)
    F = features_chunked(P)
    Y, Q = labels_chunked(P)
    names = sorted(F)
    print(f"panel {P.T}x{P.N} ready ({time.time() - t0:.0f}s)", flush=True)

    start = P.T - a.holdout_days * int(86400 // P.step)
    cand = holdout_profit(P, F, Y, Q, names, start, a.rounds)
    print("candidate holdout:", json.dumps({k: cand[k] for k in ("profit_per_day", "max_drawdown", "win_rate", "trips")}), flush=True)

    # The current model's holdout: retrain it the same way on the same window is not
    # possible (it already saw these days), so compare against the stored holdout result.
    meta_path = CURRENT / "meta.json"
    prev = json.loads(meta_path.read_text()).get("holdout") if meta_path.exists() else None
    ok = a.force or prev is None or cand["profit_per_day"] >= 0.9 * prev["profit_per_day"] or cand["profit_per_day"] > 0
    print(f"previous holdout: {prev}; promote: {ok}", flush=True)
    if not ok:
        print("Not promoted.")
        return

    model = fit(F, Y, Q, candidate_mask(P, F), names, rounds=a.rounds)
    model.meta.update({"trained_from": int(P.ts[0]), "trained_to": int(P.ts[-1]), "panel": [P.T, P.N],
                       "holdout": {k: cand[k] for k in ("profit_per_day", "max_drawdown", "win_rate", "trips")},
                       "note": f"retrain.py {time.strftime('%Y-%m-%d', time.gmtime())}, production preset"})
    tmp = ROOT / "models" / "candidate"
    if tmp.exists():
        shutil.rmtree(tmp)
    model.save(tmp)
    if CURRENT.exists():
        shutil.rmtree(CURRENT)
    tmp.rename(CURRENT)
    js = ROOT / "models" / "flip-app.json"
    export(CURRENT, js, keep=APP_BOOSTERS)
    APP_MODEL.write_text("/* Generated by research/retrain.py. Do not edit. */\nwindow.OSF_MODEL = " + js.read_text() + ";\n")
    print(f"Promoted: {CURRENT} and {APP_MODEL} ({time.time() - t0:.0f}s)")


if __name__ == "__main__":
    main()
